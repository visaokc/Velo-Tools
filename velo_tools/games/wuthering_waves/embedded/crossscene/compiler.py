def _fold_remap_identities(
        manifest: Mapping[str, Any]) -> Dict[Tuple[str, int], str]:
    records = []
    signatures: Dict[int, set[Tuple[Tuple[int, int], ...]]] = {}
    for entry in manifest.get("runtime_ibs") or ():
        if entry.get("kind") != "fold":
            continue
        tag = str(entry["ib_hash"]).lower()
        remaps = (entry.get("fold_route") or {}).get("vg_remap") or {}
        for global_raw, remap in remaps.items():
            if not remap:
                continue
            global_id = int(global_raw)
            signature = tuple(sorted(
                (int(source), int(target))
                for source, target in remap.items()
            ))
            records.append((tag, global_id, signature))
            signatures.setdefault(global_id, set()).add(signature)
    return {
        (tag, global_id): (
            f"c{global_id}remap"
            if len(signatures[global_id]) == 1
            else f"fold_{tag}_C{global_id}"
        )
        for tag, global_id, _signature in records
    }


def _fold_blend_override(
        ir: CrossSceneIR,
        body: Any,
        entry: Mapping[str, Any],
        global_id: int,
        remap: Mapping[str, Any],
        buffers: Dict[str, Any],
        identity: str,
) -> str:
    import numpy as np

    suffix = str(body.plan.suffix)
    draws = _unit_draws(body, global_id)
    blend = np.frombuffer(_buffer_bytes(body.buffers["Blend"]), np.uint8)
    blend = blend.reshape(-1, 16).copy()
    indices = np.frombuffer(_buffer_bytes(body.buffers["Index"]), np.uint32)
    ranges = [
        indices[obj.index_offset:obj.index_offset + obj.index_count]
        for obj in draws
    ]
    vertices = np.unique(np.concatenate(ranges)) if ranges else np.empty(0, np.uint32)
    table = {int(key): int(value) for key, value in remap.items()}
    for vertex in vertices:
        for seat in range(8):
            if blend[vertex, 8 + seat] and int(blend[vertex, seat]) in table:
                blend[vertex, seat] = table[int(blend[vertex, seat])]
    filename = _mesh_filename(suffix, f"Blend_{identity}")
    resource = f"ResourceBlendBuffer_{identity}{suffix}"
    command = f"CommandListOverrideSharedResources_{identity}{suffix}"
    buffers[filename] = blend.tobytes()
    ir.add_section(
        command,
        _shared_override_lines(
            body, "COMPONENT", blend_resource=resource),
        phase=IniPhase.DRAW_STACKS,
        ib_order=_unit_order(body), global_component=global_id,
        role="shared")
    ir.add_section(
        resource, [
            "type = Buffer",
            "format = DXGI_FORMAT_R8_UINT",
            "stride = 16",
            f"filename = Meshes/{filename}",
        ], phase=IniPhase.BUFFERS,
        ib_order=_unit_order(body), global_component=global_id,
        role="buffer")
    return command


def _add_fold_sections(
        ir: CrossSceneIR,
        body: Any,
        root: Any,
        cfg: Any,
        mode: str,
        texture_plan: TexturePlan,
        guards: Mapping[int, Mapping[int, str]],
        buffers: Dict[str, Any],
        section_routes: Dict[str, str],
) -> None:
    suffix = str(body.plan.suffix)
    order = _unit_order(body)
    remap_identities = _fold_remap_identities(root.manifest)
    emitted_remaps: Dict[str, str] = {}
    for entry in root.manifest.get("runtime_ibs") or ():
        if entry.get("kind") != "fold":
            continue
        tag = str(entry["ib_hash"]).lower()
        component_map = {
            int(local_id): int(global_id)
            for local_id, global_id in (entry.get("component_map") or {}).items()
        }
        components = (entry.get("runtime_layout") or {}).get("components") or ()
        remaps = (entry.get("fold_route") or {}).get("vg_remap") or {}
        for local_id, global_id in sorted(component_map.items()):
            native = components[local_id]
            first, count = _component_lines(native)
            draws = _unit_draws(body, global_id)
            name = f"TextureOverride_FoldHost_{tag}_C{local_id}{suffix}"
            lines = [
                f"hash = {tag}",
                f"match_first_index = {first}",
                f"match_index_count = {count}",
                f"$object_detected{suffix} = 1",
                f"if $mod_enabled{suffix}",
            ]
            if not draws:
                lines.extend([
                    "    handling = skip",
                    "    ; Draw skipped: component excluded by ExportSelection",
                    "endif",
                ])
                ir.add_section(
                    name, lines, phase=IniPhase.DRAW_STACKS,
                    ib_order=order, global_component=global_id,
                    role="fold_host")
                continue
            if mode == "MERGED":
                extracted = body.extracted_object.components[global_id]
                vg_offset = int(getattr(extracted, "vg_offset", 0))
                vg_count = int(getattr(extracted, "vg_count", 0))
                remap = remaps.get(str(global_id))
                if remap:
                    from .fold import _merge_offset_shift
                    shift, vg_count = _merge_offset_shift(remap)
                    vg_offset += shift
                lines.extend([
                    f"    if $merge_status_id_{global_id}{suffix} != 2",
                    f"        $\\WWMIv1\\vg_offset = {vg_offset}",
                    f"        $\\WWMIv1\\vg_count = {vg_count}",
                    f"        $merge_status_id{suffix} = "
                    f"$merge_status_id_{global_id}{suffix}",
                    f"        run = CommandListMergeSkeleton{suffix}",
                    f"        $merge_status_id_{global_id}{suffix} = "
                    f"$merge_status_id{suffix}",
                    "    endif",
                    f"    if ResourceMergedSkeleton{suffix} !== null",
                ])
                indent = "        "
            else:
                indent = "    "
            lines.extend([
                f"{indent}handling = skip",
                f"{indent}run = {_backup_name(suffix)}",
                f"{indent}run = CommandListTriggerResourceOverrides{suffix}",
            ])
            setter = texture_plan.setter(suffix, global_id, tag)
            if setter is not None:
                lines.append(f"{indent}run = {setter.name}")
            shared = f"CommandListOverrideSharedResources{suffix}"
            remap = remaps.get(str(global_id))
            if remap and mode != "MERGED":
                identity = remap_identities[(tag, global_id)]
                shared = emitted_remaps.get(identity)
                if shared is None:
                    shared = _fold_blend_override(
                        ir, body, entry, global_id, remap, buffers, identity)
                    emitted_remaps[identity] = shared
            lines.append(f"{indent}run = {shared}")
            for guard in guards.get(global_id, {}).values():
                lines.append(f"{indent}{guard} = 1")
            geometry = f"CommandListDrawGeometryComponent{global_id}{suffix}"
            lines.append(f"{indent}run = {geometry}")
            for guard in guards.get(global_id, {}).values():
                lines.append(f"{indent}{guard} = 0")
            restore_policy = (setter.restore_policy if setter is not None
                              else {"mode": "full"})
            lines.extend([
                f"{indent}run = CommandListCleanupSharedResources{suffix}",
                f"{indent}run = "
                f"{_restore_name_for(suffix, restore_policy)}",
            ])
            if mode == "MERGED":
                lines.append("    endif")
            lines.append("endif")
            ir.add_section(
                name, lines, phase=IniPhase.DRAW_STACKS,
                ib_order=order, global_component=global_id,
                role="fold_host")
            section_routes[name.casefold()] = tag


