def _format_tag_payload(section: Any, first: int, count: int) -> List[str]:
    result = []
    for line in section.lines:
        key = line.strip().split("=", 1)[0].strip().casefold()
        if key == "match_first_index":
            result.append(f"match_first_index = {first}")
        elif key == "match_index_count":
            result.append(f"match_index_count = {count}")
        else:
            result.append(str(line))
    return result


def _format_tail(section: Any) -> str:
    match = re.fullmatch(
        r"TextureOverrideComponent\d+(?:LOD\d+)?(.+)",
        str(section.name),
        re.I,
    )
    return match.group(1) if match is not None else str(section.name)


def _add_format_sections(ir: CrossSceneIR, root: Any,
                         units: Sequence[Any], plan: TexturePlan) -> None:
    sources: Dict[int, List[Any]] = {}
    anchors = []
    seen_payloads = set()

    def add_format(name: str, lines: Iterable[str], *, ib_order: int = 0,
                   global_component: Optional[int] = None) -> None:
        payload = list(lines)
        identity = tuple(
            line.strip().casefold()
            for line in payload
            if line.strip() and not line.lstrip().startswith(";")
        )
        if identity in seen_payloads:
            return
        seen_payloads.add(identity)
        ir.add_section(
            name, payload,
            phase=IniPhase.DRAW_STACKS,
            ib_order=ib_order,
            global_component=global_component,
            role="format_tag",
        )

    for section in plan.format_sections:
        if getattr(section, "kind", "") == "anchor":
            anchors.append(section)
        elif getattr(section, "kind", "") == "format_tag":
            sources.setdefault(int(section.component_id), []).append(section)
    for anchor in anchors:
        add_format(str(anchor.name), anchor.lines)
    for unit in units:
        suffix = str(unit.plan.suffix)
        order = _unit_order(unit)
        route = ("base" if unit.plan.kind == "body"
                 else str(unit.plan.ib_hash).lower())
        layout = _unit_layout(unit, root)
        components = layout.get("components") or ()
        lods = _unit_lods(unit, root)
        for local_id, global_id_raw in unit.plan.component_map:
            global_id = int(global_id_raw)
            if plan.setter(suffix, global_id, route) is None:
                continue
            component = components[local_id]
            first, count = _component_lines(component)
            for source in sources.get(global_id, ()):
                if getattr(source, "level", None) is not None:
                    continue
                tail = _format_tail(source)
                name = (f"TextureOverrideComponent{global_id}{tail}{suffix}"
                        if route == "base" else
                        f"TextureOverrideRouteFormat_{route}_C{local_id}_Base_"
                        f"{tail}{suffix}")
                add_format(
                    name, _format_tag_payload(source, first, count),
                    ib_order=order,
                    global_component=global_id,
                )
                for lod in lods:
                    lod_component = lod["components"][local_id]
                    if lod_component is None:
                        continue
                    lod_first, lod_count = _component_lines(lod_component)
                    lod_name = (
                        f"TextureOverrideComponent{global_id}LOD"
                        f"{int(lod['level'])}{tail}{suffix}"
                        if route == "base" else
                        f"TextureOverrideRouteFormat_{route}_C{local_id}_L"
                        f"{int(lod['level'])}_{tail}{suffix}")
                    add_format(
                        lod_name,
                        _format_tag_payload(source, lod_first, lod_count),
                        ib_order=order,
                        global_component=global_id,
                    )
    body = units[0]
    body_suffix = str(body.plan.suffix)
    body_order = _unit_order(body)
    for entry in root.manifest.get("runtime_ibs") or ():
        if entry.get("kind") != "fold":
            continue
        route = str(entry["ib_hash"]).lower()
        components = (entry.get("runtime_layout") or {}).get("components") or ()
        for local_raw, global_raw in (entry.get("component_map") or {}).items():
            local_id, global_id = int(local_raw), int(global_raw)
            if plan.setter(body_suffix, global_id, route) is None:
                continue
            component = components[local_id]
            first, count = _component_lines(component)
            for source in sources.get(global_id, ()):
                if getattr(source, "level", None) is not None:
                    continue
                tail = _format_tail(source)
                add_format(
                    f"TextureOverrideRouteFormat_{route}_C{local_id}_Base_"
                    f"{tail}{body_suffix}",
                    _format_tag_payload(source, first, count),
                    ib_order=body_order,
                    global_component=global_id,
                )
                for level, lod in enumerate(component.get("lods") or (), start=1):
                    lod_first, lod_count = _component_lines(lod)
                    add_format(
                        f"TextureOverrideRouteFormat_{route}_C{local_id}_L"
                        f"{level}_{tail}{body_suffix}",
                        _format_tag_payload(source, lod_first, lod_count),
                        ib_order=body_order,
                        global_component=global_id,
                    )


def _add_texture_sections(ir: CrossSceneIR, root: Any,
                          units: Sequence[Any], plan: TexturePlan,
                          textures: Sequence[Any]) -> None:
    emitted_setters = set()
    for setter in sorted(
            plan.setters.values(),
            key=lambda item: (
                int(item.suffix.removeprefix("_ib")),
                item.component_id,
                item.route,
            )):
        identity = setter.name.casefold()
        if identity in emitted_setters:
            continue
        emitted_setters.add(identity)
        ir.add_section(
            setter.name, setter.lines,
            phase=IniPhase.DRAW_STACKS,
            ib_order=int(setter.suffix.removeprefix("_ib")),
            global_component=setter.component_id,
            role="slot_setter",
        )
    _add_format_sections(ir, root, units, plan)
    for name, texture in sorted(plan.resources.items()):
        match = re.search(r"_C(\d+)_", name)
        component = int(match.group(1)) if match else None
        suffix_match = re.search(r"_ib(\d+)$", name)
        order = int(suffix_match.group(1)) if suffix_match else 0
        ir.add_section(
            name, [f"filename = Textures/{texture.filename}"],
            phase=IniPhase.TEXTURES,
            ib_order=order,
            global_component=component,
            role="buffer",
        )

    unit_owners = _global_to_unit_components(units)
    by_hash = {str(texture.hash).lower(): texture for texture in textures}
    for texture_hash in sorted(plan.hash_fallback_components):
        texture = by_hash[texture_hash]
        variables = []
        for component_id in sorted(plan.hash_fallback_components[texture_hash]):
            for unit, _local_id in unit_owners.get(component_id, ()):
                variable = f"$object_detected{unit.plan.suffix}"
                if variable not in variables:
                    variables.append(variable)
        if not variables:
            continue
        resource = f"Resource_Texture_{texture_hash}"
        override = f"TextureOverride_Texture_{texture_hash}"
        ir.add_section(
            resource, [f"filename = Textures/{texture.filename}"],
            phase=IniPhase.TEXTURES, role="hash_pair")
        ir.add_section(
            override, [
                f"hash = {texture_hash}",
                "match_priority = 0",
                f"if {' || '.join(variables)}",
                f"    this = {resource}",
                "endif",
            ], phase=IniPhase.TEXTURES, role="hash_pair")


def _add_footer(ir: CrossSceneIR, cfg: Any) -> None:
    ir.footer.extend([
        "; ===== Autogenerated =====",
        "; This mod.ini was generated by Velo Tools cross-scene typed compiler "
        f"v{getattr(cfg, 'wwmi_tools_version', '')} and requires WWMI "
        f"v{getattr(cfg, 'required_wwmi_version', '')}+ to function",
    ])


def _with_checksum(text: str) -> str:
    body = text.strip() + "\n"
    digest = hashlib.sha256(body.encode("utf-8")).hexdigest()
    return body + f"; SHA256 CHECKSUM: {digest}\n"


def _validate_ir(ir: CrossSceneIR, buffers: Mapping[str, Any],
                 textures: Sequence[Any], logo: Optional[Path],
                 mode: str) -> Dict[str, Any]:
    ir.assert_unique()
    definitions = {
        definition.casefold()
        for section in ir.sections
        for definition in section.definitions
    }
    dangling = sorted({
        reference
        for section in ir.sections
        for reference in section.references
        if "\\" not in reference and reference.casefold() not in definitions
    })
    available = {f"Meshes/{name}".casefold() for name in buffers}
    available.update(
        f"Textures/{texture.filename}".casefold() for texture in textures)
    if logo is not None and logo.is_file():
        available.add("textures/logo.dds")
    missing = []
    for section in ir.sections:
        for line in section.lines:
            match = re.match(r"^\s*filename\s*=\s*(\S+)\s*$", line, re.I)
            if match and match.group(1).casefold() not in available:
                missing.append(match.group(1))
    text = ir.render()
    if mode != "MERGED":
        forbidden = (
            "ResourceMergedSkeleton",
            "CommandListMergeSkeleton",
            "CommandListUpdateMergedSkeleton",
            "BlendRemap",
            "$merge_status_id",
        )
        leaked = [token for token in forbidden if token.casefold() in text.casefold()]
        if leaked:
            raise CrossSceneCompileError(
                "PFM/Per-Component hard gate failed: " + ", ".join(leaked))
    if dangling or missing:
        raise CrossSceneCompileError(
            "compiled typed IR is not closed: dangling=%s missing=%s"
            % (dangling, sorted(set(missing))))
    return {
        "sections": len(ir.sections),
        "dangling": [],
        "missing": [],
        "sound": True,
    }


def _compile_cross_scene_legacy(units: Sequence[Any], manifest: Mapping[str, Any],
                                settings: CompilerSettings) -> CompiledMod:
    """Compile final INI, buffers and texture delivery directly from memory units."""
    cfg = settings.cfg
    if bool(getattr(cfg, "use_custom_template", False)):
        raise CrossSceneCompileError(
            "跨场景导出不支持任意自定义 Jinja INI 模板；请关闭“使用自定义模板”后重试。")
    if bool(getattr(cfg, "custom_template_live_update", False)):
        raise CrossSceneCompileError(
            "跨场景导出不支持实时更新 INI 模板；请关闭实时更新后重试。")
    if not units or units[0].plan.kind != "body":
        raise CrossSceneCompileError("first ExportUnit must be the body resource domain")
    root = Path(settings.root)
    if bool(getattr(cfg, "partial_export", False)):
        buffers = _collect_unit_buffers(units)
        return CompiledMod(
            ini_text="",
            buffers=buffers,
            textures=(),
            report={
                "roles": ["body"] + [str(entry["ib_hash"])
                                      for entry in manifest.get("runtime_ibs") or []],
                "ib_count": 1 + len(manifest.get("runtime_ibs") or []),
                "slot_style": False,
                "no_child_exports": True,
                "sections": 0,
                "dangling": [],
                "missing": [],
                "sound": True,
            },
        )
    cfg_view = _normalized_cfg(cfg)
    mode = cfg_view.mod_skeleton_type
    textures = (_root_textures(root, cfg)
                if settings.selection.objects else ())
    ini_textures = _ini_textures(textures)
    try:
        from ..._wwmi_core.migoto_io.blender_interface.utility import resolve_path
        logo_source = resolve_path(cfg.mod_logo)
    except Exception:
        logo_source = Path(str(getattr(cfg, "mod_logo", "")))

    template = _template_source(mode, bool(cfg.comment_ini))
    body = units[0]
    body_component_ids = [global_id
                          for _local_id, global_id in body.plan.component_map]
    body_template = specialize_unit_template(template, body.plan.suffix)
    body_text = _render(
        body_template,
        _maker(body, cfg_view, ini_textures, logo_source),
        component_ids=body_component_ids,
    )
    ir = (CrossSceneIR.parse(body_text) if _unit_has_geometry(body)
          else _empty_body_ir(body_text, body))
    section_routes: Dict[str, str] = {}
    for section in ir.sections:
        if re.search(r"CommandListDrawComponent\d+_ib0$", section.name, re.I):
            section_routes[section.name.casefold()] = "base"

    fragment_source = _unit_fragment_source(template, mode)
    for unit in units[1:]:
        if not _unit_has_geometry(unit):
            continue
        specialized = specialize_unit_template(fragment_source, unit.plan.suffix)
        component_ids = [global_id for _local_id, global_id in unit.plan.component_map]
        fragment = _render(
            specialized,
            _maker(unit, cfg_view, (), logo_source),
            component_ids=component_ids,
        )
        fragment_ir = CrossSceneIR.parse(fragment)
        fragment_ir.sections = [
            section for section in fragment_ir.sections
            if section.name.casefold() != "commandlisttriggerresourceoverrides"
        ]
        for section in fragment_ir.sections:
            match = re.search(r"CommandListDrawComponent(\d+)", section.name, re.I)
            if match:
                section_routes[section.name.casefold()] = unit.plan.ib_hash.lower()
        ir.sections.extend(fragment_ir.sections)

    for unit in units:
        _append_empty_unit_routes(ir, unit)

    _append_unit_globals(ir, units, cfg, mode)
    _compile_present(ir, units, mode, cfg)
    buffers = _collect_unit_buffers(units)
    _append_fold_units(ir, body, manifest, cfg, buffers, section_routes)
    ir.assert_unique()
    text = ir.render()

    plan = _slot_plan(
        settings.context,
        root,
        cfg,
        settings.selection,
        manifest,
        ini_textures,
        selected_component_ids=_drawn_component_ids(units),
    )
    if plan is not None:
        from ..slot_textures import transform
        _add_scoped_setter_aliases(plan, section_routes)
        text = transform.apply(text, plan, section_routes=section_routes)
        domain_suffixes = {
            str(unit.plan.ib_hash).lower(): unit.plan.suffix
            for unit in units[1:]
        }
        domain_suffixes.update({
            str(entry["ib_hash"]).lower(): body.plan.suffix
            for entry in manifest.get("runtime_ibs") or []
            if entry.get("kind") == "fold"
        })
        text = _clone_route_format_tags(
            text, manifest, plan, domain_suffixes=domain_suffixes)

    final_ir = CrossSceneIR.parse(text)
    from ...xscene_textures import cross_scene_root_texture_component_ids
    texture_components = cross_scene_root_texture_component_ids(root, manifest)
    _apply_domain_object_gates(final_ir, units, texture_components)
    final_ir.assert_unique()
    _assert_object_domain_isolation(final_ir.render(), units)
    from ..._wwmi_core.blender_export.ini_maker import IniMaker
    text = IniMaker.with_checksum(final_ir.render())
    final_ir = CrossSceneIR.parse(text)
    text = final_ir.render()
    report = _validate_compiled(text, buffers, textures, logo_source)
    report.update({
        "roles": ["body"] + [str(entry["ib_hash"])
                              for entry in manifest.get("runtime_ibs") or []],
        "ib_count": 1 + len(manifest.get("runtime_ibs") or []),
        "slot_style": plan is not None,
        "no_child_exports": True,
    })
    if plan is not None:
        report.update({
            "slot_branch_expectations": dict(plan.branch_contract),
            "slot_restore_contract": dict(plan.restore_contract),
            "slot_component_route_lists": dict(plan.component_route_lists),
            "slot_root_catalog_hash_fallback_components": list(
                getattr(plan, "root_catalog_hash_fallback_components", ())),
            "tex_slot": sorted(plan.covered_resource_indices),
            "tex_blindzone": list(plan.blind_zone),
        })
    return CompiledMod(
        text, buffers, textures, plan, section_routes, report,
        ini_ir=final_ir,
    )


def _prepare_shape_key_domains(
        units: Sequence[Any], cfg: Any,
) -> Tuple[Mapping[int, int], Tuple[Any, ...]]:
    if not __package__:
        return {}, tuple(None for _unit in units)
    try:
        from ..shapekey.runtime import prepare_units
        return prepare_units(
            units,
            enabled=bool(getattr(
                cfg, "unrestricted_custom_shape_keys", True)),
        )
    except Exception as exc:
        try:
            from ..shapekey.planner import ShapeKeyPlanError
        except Exception:
            ShapeKeyPlanError = ValueError
        if isinstance(exc, ShapeKeyPlanError):
            raise CrossSceneCompileError(
                f"WWMI ShapeKey export failed: {exc}") from exc
        raise


def _add_shape_key_controls(
        ir: CrossSceneIR,
        units: Sequence[Any],
        channels: Mapping[int, int],
        plans: Sequence[Any],
) -> None:
    active = [
        (unit, plan) for unit, plan in zip(units, plans)
        if plan is not None and plan.has_external
    ]
    if not active:
        return
    from ..shapekey.generator import (
        control_constant_lines,
        control_present_lines,
        validate_channel_lines,
    )
    try:
        validate_channel_lines(
            (line for section in ir.sections for line in section.lines),
            channels,
        )
    except ValueError as exc:
        raise CrossSceneCompileError(
            f"WWMI ShapeKey export failed: {exc}") from exc
    suffixes = tuple(str(unit.plan.suffix) for unit, _plan in active)
    ir.get("Constants").lines.extend(
        control_constant_lines(channels, suffixes))
    ir.get("Present").lines.extend(
        control_present_lines(channels, suffixes))


def compile_cross_scene(units: Sequence[Any], root: Any,
                        settings: CompilerSettings) -> CompiledMod:
    """Compile one final mod from typed units and a root-authoritative catalog."""
    cfg = settings.cfg
    if bool(getattr(cfg, "use_custom_template", False)):
        raise CrossSceneCompileError(
            "跨场景导出不支持任意自定义 Jinja INI 模板；请关闭“使用自定义模板”后重试。")
    if bool(getattr(cfg, "custom_template_live_update", False)):
        raise CrossSceneCompileError(
            "跨场景导出不支持实时更新 INI 模板；请关闭实时更新后重试。")
    if not units or units[0].plan.kind != "body":
        raise CrossSceneCompileError(
            "first ExportUnit must be the body resource domain")
    if not hasattr(root, "manifest") or not hasattr(root, "metadata"):
        raise CrossSceneCompileError(
            "compile_cross_scene requires a loaded CrossSceneRoot")

    channels, shape_plans = _prepare_shape_key_domains(units, cfg)
    if (bool(getattr(cfg, "partial_export", False))
            and any(plan is not None and plan.parsed.custom_records
                    for plan in shape_plans)):
        raise CrossSceneCompileError(
            "自定义 ShapeKey 数据发生变化时必须执行完整导出：请关闭 Partial Export 后重试。")
    buffers = _collect_unit_buffers(units)
    roles = ["body"] + [
        str(entry["ib_hash"])
        for entry in root.manifest.get("runtime_ibs") or ()
    ]
    if bool(getattr(cfg, "partial_export", False)):
        return CompiledMod(
            ini_text="",
            buffers=buffers,
            textures=(),
            report={
                "roles": roles,
                "ib_count": len(roles),
                "slot_style": False,
                "no_child_exports": True,
                "typed_ir": True,
                "sections": 0,
                "dangling": [],
                "missing": [],
                "sound": True,
            },
        )

    mode = _mode(cfg)
    if mode not in {"COMPONENT", "MERGED"}:
        raise CrossSceneCompileError(f"unknown skeleton mode {mode!r}")
    textures = (_root_textures(root, cfg)
                if settings.selection.objects else ())
    ini_textures = _ini_textures(textures)
    texture_plan = _texture_plan(units, root, settings, ini_textures)
    try:
        from ..._wwmi_core.migoto_io.blender_interface.utility import resolve_path
        logo_source = resolve_path(cfg.mod_logo)
    except Exception:
        logo_source = Path(str(getattr(cfg, "mod_logo", "")))

    ir = CrossSceneIR(preamble=[
        "; WWMI cross-scene mod (schema-v3 typed IR)",
    ])
    body = units[0]
    guards = _split_guards(root, body)
    section_routes: Dict[str, str] = {}
    _add_state_sections(
        ir, units, root, cfg, mode, texture_plan, guards)
    _add_shape_key_controls(ir, units, channels, shape_plans)
    _add_mod_info_sections(ir, units, cfg, logo_source)
    if mode == "MERGED":
        _add_merged_skeleton_sections(ir, units, cfg)
    fold_callers = _fold_callers(root)
    for unit in units:
        _add_unit_draw_sections(
            ir, unit, root, cfg, mode, texture_plan, guards,
            fold_callers, section_routes)
    _add_fold_sections(
        ir, body, root, cfg, mode, texture_plan, guards,
        buffers, section_routes)
    for unit in units:
        _add_shape_sections(ir, unit, cfg, mode)
        if unit is body:
            for entry in root.manifest.get("runtime_ibs") or ():
                if entry.get("kind") != "fold":
                    continue
                component_ids = tuple(
                    int(global_id)
                    for global_id in (entry.get("component_map") or {}).values()
                )
                _add_fold_morph_sections(
                    ir, body, entry, component_ids, cfg, mode, buffers)
        _add_buffer_sections(ir, unit, mode)
    _add_texture_sections(ir, root, units, texture_plan, ini_textures)
    _add_footer(ir, cfg)

    report = _validate_ir(ir, buffers, textures, logo_source, mode)
    rendered = ir.render()
    text = _with_checksum(rendered)
    report.update({
        "roles": roles,
        "ib_count": len(roles),
        "slot_style": texture_plan.raw_plan is not None,
        "no_child_exports": True,
        "typed_ir": True,
        "slot_branch_expectations": dict(texture_plan.branch_contract),
        "slot_restore_contract": dict(texture_plan.restore_contract),
        "slot_component_route_lists": dict(texture_plan.route_lists),
        "slot_root_catalog_hash_fallback_components": {
            texture_hash: sorted(component_ids)
            for texture_hash, component_ids
            in sorted(texture_plan.hash_fallback_components.items())
        },
        "tex_slot": sorted(texture_plan.assigned_components),
        "tex_blindzone": sorted(texture_plan.hash_fallback_components),
        "external_shape_key_ids": sorted(channels),
        "shape_key_domains": [
            {
                "identity": str(unit.plan.identity),
                "resource_domain": str(unit.plan.resource_domain),
                "native_batch_records": list(
                    plan.parsed.native_batch_record_counts),
                "native_deform_counts": [
                    int(batch.shapekey_count)
                    for batch in (
                        getattr(unit.extracted_object.shapekeys, "batches", ())
                        or ())
                ],
                "external_records": (
                    int(plan.external.record_count)
                    if plan.external is not None else 0),
                "stripped_custom_records": (
                    0 if plan.external is not None
                    else len(plan.parsed.custom_records)),
            }
            for unit, plan in zip(units, shape_plans)
            if plan is not None
        ],
    })
    return CompiledMod(
        ini_text=text,
        buffers=buffers,
        textures=textures,
        slot_plan=texture_plan,
        section_routes=section_routes,
        report=report,
        ini_ir=ir,
        external_shape_keys=any(
            plan is not None and plan.has_external for plan in shape_plans),
    )


def _safe_meshes_path(output: Path) -> Path:
    output = output.resolve()
    meshes = (output / "Meshes").resolve()
    if meshes.parent != output:
        raise CrossSceneCompileError("refusing to rebuild Meshes outside output root")
    return meshes


def _write_ini_with_backup(path: Path, text: str) -> None:
    from ..._wwmi_core.blender_export.ini_maker import IniMaker
    if path.is_file() and IniMaker.is_ini_edited(path):
        stamp = datetime.now().strftime("%Y-%m-%d %H-%M-%S")
        path.rename(path.with_name(f"{path.name} {stamp}.BAK"))
    path.write_text(text, encoding="utf-8")


def write_compiled_mod(compiled: CompiledMod, output: Path | str,
                       gates: OutputGates) -> Dict[str, Any]:
    """Apply native output gates after compilation; never creates child outputs."""
    output = Path(output)
    output.mkdir(parents=True, exist_ok=True)
    meshes = _safe_meshes_path(output)
    if not gates.partial_export:
        if meshes.exists():
            shutil.rmtree(meshes)
        meshes.mkdir(parents=True, exist_ok=True)
    else:
        meshes.mkdir(parents=True, exist_ok=True)
    for filename, buffer in compiled.buffers.items():
        (meshes / filename).write_bytes(_buffer_bytes(buffer))
    if not gates.partial_export and __package__:
        from ..shapekey.generator import write_hlsl_assets
        write_hlsl_assets(output, compiled.external_shape_keys)

    ini_written = False
    textures_written = False
    if not gates.partial_export:
        if gates.copy_textures:
            texture_dir = output / "Textures"
            texture_dir.mkdir(parents=True, exist_ok=True)
            for texture in compiled.textures:
                target = texture_dir / texture.filename
                if not target.exists():
                    shutil.copy2(texture.path, target)
            if gates.logo_source is not None and gates.logo_source.is_file():
                logo = texture_dir / "Logo.dds"
                if not logo.exists():
                    shutil.copy2(gates.logo_source, logo)
            textures_written = True
        if gates.write_ini:
            _write_ini_with_backup(output / "mod.ini", compiled.render_ini())
            ini_written = True
    report = dict(compiled.report)
    report.update({
        "final_ini_written": ini_written,
        "final_textures_written": textures_written,
        "buffers_written": sorted(compiled.buffers),
        "root_dds_files": len(compiled.textures),
        "sound": bool(compiled.report.get("sound", True)),
    })
    return report
