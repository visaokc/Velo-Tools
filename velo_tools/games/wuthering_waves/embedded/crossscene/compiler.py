def _buffer_format(buffer: Any) -> Tuple[str, int]:
    layout = getattr(buffer, "layout", None)
    semantics = getattr(layout, "semantics", ()) or ()
    if not semantics:
        raise CrossSceneCompileError("encoded buffer has no layout semantics")
    fmt = semantics[0].get_format()
    return str(fmt), int(getattr(layout, "stride", 0))


def _add_buffer_sections(ir: CrossSceneIR, unit: Any, mode: str) -> None:
    if not _unit_has_geometry(unit):
        return
    suffix = str(unit.plan.suffix)
    order = _unit_order(unit)
    ir.add_section(
        f"ResourceBypassVB0{suffix}", (),
        phase=IniPhase.BUFFERS, ib_order=order, role="buffer")
    for name, buffer in unit.buffers.items():
        fmt, stride = _buffer_format(buffer)
        lines = ["type = Buffer", f"format = {fmt}"]
        if not (mode == "MERGED" and "BlendRemap" in str(name)):
            lines.append(f"stride = {stride}")
        lines.append(
            f"filename = Meshes/{_mesh_filename(suffix, str(name))}")
        ir.add_section(
            _buffer_resource(str(name), suffix), lines,
            phase=IniPhase.BUFFERS, ib_order=order, role="buffer")
        if (mode == "MERGED" and str(name) == "Blend"
                and int(getattr(unit.merged_object, "blend_remap_count", 0)) > 0):
            ir.add_section(
                f"ResourceBlendBufferNoStride{suffix}", [
                    "type = Buffer",
                    f"format = {fmt}",
                    f"filename = Meshes/{_mesh_filename(suffix, str(name))}",
                ], phase=IniPhase.BUFFERS, ib_order=order, role="buffer")


def _add_merged_skeleton_sections(ir: CrossSceneIR, units: Sequence[Any],
                                  cfg: Any) -> None:
    hashes = {
        str(getattr(unit.extracted_object, "cb4_hash", "")).lower()
        for unit in units if _unit_has_geometry(unit)
    }
    if len(hashes) > 1:
        raise CrossSceneCompileError(
            "MERGED cross-scene units disagree on the bone-data CB hash")
    if hashes:
        ir.add_section(
            "TextureOverrideMarkBoneDataCB", [
                f"hash = {next(iter(hashes))}",
                "match_priority = 0",
                "filter_index = 3381.7777",
            ], phase=IniPhase.DRAW_STACKS, role="shared")
    scale = float(getattr(cfg, "skeleton_scale", 1.0))
    for unit in units:
        if not _unit_has_geometry(unit):
            continue
        suffix = str(unit.plan.suffix)
        order = _unit_order(unit)
        remap_count = int(getattr(unit.merged_object, "blend_remap_count", 0))
        update = []
        for _local_id, global_id in unit.plan.component_map:
            update.append(f"$merge_status_id_{global_id}{suffix} = 0")
        update.extend([
            f"ResourceMergedSkeleton{suffix} = copy "
            f"ResourceMergedSkeletonRW{suffix}",
            f"ResourceExtraMergedSkeleton{suffix} = copy "
            f"ResourceExtraMergedSkeletonRW{suffix}",
        ])
        if remap_count > 0:
            update.append(f"run = CommandListRemapMergedSkeleton{suffix}")
        ir.add_section(
            f"CommandListUpdateMergedSkeleton{suffix}", update,
            phase=IniPhase.DRAW_STACKS, ib_order=order, role="shared")
        ir.add_section(
            f"CommandListMergeSkeleton{suffix}", [
                f"if $merge_status_id{suffix} == 0",
                "    if vs-cb4 == 3381.7777",
                "        cs-cb8 = ref vs-cb4",
                f"        cs-u6 = ResourceMergedSkeletonRW{suffix}",
                f"        $\\WWMIv1\\custom_mesh_scale = {scale:.2f}",
                "        run = CustomShader\\WWMIv1\\SkeletonMerger",
                f"        $merge_status_id{suffix} = 1",
                "    endif",
                "endif",
                f"if $merge_status_id{suffix} == 1",
                "    if vs-cb4 == 3381.7777 && vs-cb3 == 3381.7777",
                "        cs-cb8 = ref vs-cb3",
                f"        cs-u6 = ResourceExtraMergedSkeletonRW{suffix}",
                f"        $\\WWMIv1\\custom_mesh_scale = {scale:.2f}",
                "        run = CustomShader\\WWMIv1\\SkeletonMerger",
                f"        $merge_status_id{suffix} = 2",
                "    endif",
                "endif",
            ], phase=IniPhase.DRAW_STACKS, ib_order=order, role="shared")
        size = 1536 if remap_count > 0 else 768
        for name, lines in (
                (f"ResourceMergedSkeleton{suffix}", []),
                (f"ResourceMergedSkeletonRW{suffix}", [
                    "type = RWBuffer",
                    "format = R32G32B32A32_FLOAT",
                    f"array = {size}",
                ]),
                (f"ResourceExtraMergedSkeleton{suffix}", []),
                (f"ResourceExtraMergedSkeletonRW{suffix}", [
                    "type = RWBuffer",
                    "format = R32G32B32A32_FLOAT",
                    f"array = {size}",
                ])):
            ir.add_section(
                name, lines, phase=IniPhase.BUFFERS,
                ib_order=order, role="buffer")
        if remap_count > 0:
            _add_merged_remap_sections(ir, unit)


