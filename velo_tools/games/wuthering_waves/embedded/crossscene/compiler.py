def _restore_slot(policy: Mapping[str, Any]) -> Optional[int]:
    mode = str(policy.get("mode") or "full").lower()
    if mode not in {"persistent", "except"}:
        return None
    try:
        slot = int(policy.get(
            "persistent_slot" if mode == "except" else "slot"))
    except (TypeError, ValueError):
        return None
    return slot if 0 <= slot <= 8 else None


def _backup_name(suffix: str) -> str:
    return f"CommandListBackupPixelShaderResources{suffix}"


def _restore_name_for(suffix: str, policy: Mapping[str, Any]) -> str:
    slot = _restore_slot(policy)
    if slot is None:
        return f"CommandListRestorePixelShaderResources{suffix}"
    return f"CommandListRestorePixelShaderResourcesExceptT{slot}{suffix}"


def _add_state_sections(ir: CrossSceneIR, units: Sequence[Any], root: Any,
                        cfg: Any, mode: str, texture_plan: TexturePlan,
                        guards: Mapping[int, Mapping[int, str]]) -> None:
    constants: List[str] = []
    toggle_globals: set[str] = set()
    formatter = None
    if bool(getattr(cfg, "use_ini_toggles", False)):
        from ..._wwmi_core.blender_export.text_formatter import TextFormatter
        formatter = TextFormatter()
    for unit in units:
        suffix = str(unit.plan.suffix)
        order = _unit_order(unit)
        if constants:
            constants.append("")
        constants.append(f"; --- ib{order} ---")
        if order == 0:
            for component_guards in guards.values():
                for variable in component_guards.values():
                    constants.append(f"global {variable} = 0")
        constants.extend([
            f"global $required_wwmi_version{suffix} = "
            f"{_version_float(getattr(cfg, 'required_wwmi_version', '1.0'))}",
            f"global $object_guid{suffix} = "
            f"{int(getattr(unit.extracted_object, 'index_count', 0))}",
            f"global $mesh_vertex_count{suffix} = "
            f"{int(getattr(unit.merged_object, 'vertex_count', 0))}",
            f"global $shapekey_vertex_count{suffix} = "
            f"{int(getattr(unit.merged_object.shapekeys, 'vertex_count', 0))}",
        ])
        for index, batch in enumerate(
                getattr(unit.merged_object.shapekeys, "batches", ()) or ()):
            constants.extend([
                f"global $shapekey_vertex_offset_batch{index}{suffix} = "
                f"{int(_value(batch, 'vertex_offset', 0))}",
                f"global $shapekey_vertex_count_batch{index}{suffix} = "
                f"{int(_value(batch, 'vertex_count', 0))}",
            ])
        constants.extend([
            f"global $mod_id{suffix} = -1000",
            f"global $mod_enabled{suffix} = 0",
            f"global $object_detected{suffix} = 0",
        ])
        if _unit_lods(unit, root):
            constants.append(f"global $lod_level{suffix} = 0")
        if mode == "MERGED" and _unit_has_geometry(unit):
            constants.extend([
                f"global $state_id{suffix} = 0",
                f"global $merge_status_id{suffix} = 0",
            ])
            for _local_id, global_id in unit.plan.component_map:
                constants.append(
                    f"global $merge_status_id_{global_id}{suffix} = 0")
        if formatter is not None:
            for component in getattr(unit.merged_object, "components", ()) or ():
                for obj in getattr(component, "objects", ()) or ():
                    toggle_globals.add(formatter.format_ini_drawvar(obj.name))
    if formatter is not None:
        for var in cfg.ini_toggles.vars:
            constants.append(
                f"global persist {formatter.format_ini_swapvar(var.name)} = "
                f"{getattr(var, 'default_state', None) or 0}")
        for name in sorted(toggle_globals):
            constants.append(f"global {name} = 1")
    raw = texture_plan.raw_plan
    if raw is not None and bool(getattr(raw, "multi_form", False)):
        constants.append(
            f"global $velo_form_id = {int(getattr(raw, 'default_form_id', 1))}")
        for name in getattr(raw, "extra_globals", ()) or ():
            constants.append(f"global {name} = 0")
    ir.add_section(
        "Constants", constants, phase=IniPhase.MOD_STATE,
        role="constants")

    present: List[str] = []
    for unit in units:
        suffix = str(unit.plan.suffix)
        order = _unit_order(unit)
        if present:
            present.append("")
        present.extend([
            f"; --- ib{order} ---",
            f"if $object_detected{suffix}",
            f"    if $mod_enabled{suffix}",
            f"        post $object_detected{suffix} = 0",
        ])
        if bool(getattr(cfg, "use_ini_toggles", False)) and order == 0:
            present.append(f"        run = CommandListProcessToggles{suffix}")
        if mode == "MERGED" and _unit_has_geometry(unit):
            if int(getattr(unit.merged_object, "blend_remap_count", 0)) > 0:
                present.append(
                    f"        run = CommandListInitializeBlendRemaps{suffix}")
            present.append(f"        run = CommandListUpdateMergedSkeleton{suffix}")
        present.extend([
            "    else",
            f"        if $mod_id{suffix} == -1000",
            f"            run = CommandListRegisterMod{suffix}",
            "        endif",
            "    endif",
            "endif",
        ])
    raw = texture_plan.raw_plan
    if raw is not None:
        watchdog = list(getattr(raw, "watchdog_lines", ()) or ())
        if watchdog:
            present.extend([""] + watchdog)
    ir.add_section(
        "Present", present, phase=IniPhase.MOD_STATE, role="present")

    if formatter is not None:
        detected = " || ".join(
            f"$object_detected{unit.plan.suffix}" for unit in units)
        for var in cfg.ini_toggles.vars:
            hotkeys = getattr(var, "hotkeys", None)
            if not hotkeys:
                continue
            key_lines = [f"condition = {detected}"]
            key_lines.extend(
                f"key = {hotkey}"
                for hotkey in formatter.format_hotkeys(hotkeys)
            )
            key_lines.extend([
                "type = cycle",
                f"{formatter.format_ini_swapvar(var.name)} = "
                + ", ".join(str(state.name) for state in var.states),
            ])
            ir.add_section(
                "KeySwap" + formatter.format_name_camel_case(var.name),
                key_lines, phase=IniPhase.MOD_STATE, role="key")
        toggle_lines = []
        for object_name, condition in cfg.ini_toggles.compile_conditions().items():
            toggle_lines.append(
                f"{formatter.format_ini_drawvar(object_name)} = {condition}")
        ir.add_section(
            "CommandListProcessToggles_ib0", toggle_lines,
            phase=IniPhase.MOD_STATE, role="toggle")


def _mod_info_lines(value: Any, fallback: str) -> List[str]:
    text = str(value or "").strip()
    if text:
        return ["type = Buffer", f'data = "{text}"']
    return ["; type = Buffer", f'; data = "{fallback}"']


