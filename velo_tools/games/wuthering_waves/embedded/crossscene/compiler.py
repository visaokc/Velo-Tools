class IniPhase(IntEnum):
    MOD_STATE = 10
    MOD_INFO = 20
    DRAW_STACKS = 30
    TEXTURES = 40
    SHAPE_KEYS = 50
    BUFFERS = 60
    AUTOGENERATED = 70


_PHASE_TITLES = {
    IniPhase.MOD_STATE: "Mod State / Constants / Present",
    IniPhase.MOD_INFO: "Mod Info",
    IniPhase.DRAW_STACKS: "Draw Call Stacks Processing",
    IniPhase.TEXTURES: "Shading: Textures",
    IniPhase.SHAPE_KEYS: "Shape Keys",
    IniPhase.BUFFERS: "Buffer Resources",
    IniPhase.AUTOGENERATED: "Autogenerated",
}


@dataclass
class IniSectionIR:
    name: str
    lines: List[str]
    phase: IniPhase = IniPhase.AUTOGENERATED
    ib_order: int = 0
    global_component: Optional[int] = None
    role: str = ""
    definitions: Tuple[str, ...] = ()
    references: Tuple[str, ...] = ()
    ordinal: int = 0

    def __post_init__(self) -> None:
        if not self.definitions:
            self.definitions = (self.name,)
        if not self.references:
            text = "\n".join(self.lines)
            self.references = tuple(dict.fromkeys(
                reference for reference in _LOCAL_REF_RE.findall(text)
                if "\\" not in reference
            ))


@dataclass(frozen=True)
class SectionLayoutPolicy:
    role_order: Mapping[str, int] = field(default_factory=lambda: {
        "constants": 0,
        "present": 10,
        "key": 20,
        "register": 30,
        "toggle": 40,
        "mod_info": 0,
        "shared": 0,
        "matcher": 10,
        "draw_wrapper": 20,
        "geometry": 21,
        "fold_host": 30,
        "slot_setter": 40,
        "format_tag": 50,
        "hash_resource": 0,
        "hash_override": 1,
        "shape_override": 0,
        "shape_command": 10,
        "buffer": 0,
        "support": 10,
        "footer": 0,
    })

    def key(self, section: IniSectionIR) -> Tuple[int, int, int, int, int]:
        component = (-1 if section.global_component is None
                     else int(section.global_component))
        return (
            int(section.phase),
            int(section.ib_order),
            component,
            int(self.role_order.get(section.role, 100)),
            int(section.ordinal),
        )


@dataclass
class CrossSceneIR:
    preamble: List[str] = field(default_factory=list)
    sections: List[IniSectionIR] = field(default_factory=list)
    footer: List[str] = field(default_factory=list)
    layout: SectionLayoutPolicy = field(default_factory=SectionLayoutPolicy)
    _next_ordinal: int = field(default=0, init=False, repr=False)

    @classmethod
    def parse(cls, text: str) -> "CrossSceneIR":
        result = cls()
        current = None
        for line in text.splitlines():
            match = _HEADER_RE.match(line)
            if match:
                current = IniSectionIR(
                    match.group(1), [], ordinal=result._next_ordinal)
                result._next_ordinal += 1
                result.sections.append(current)
            elif current is None:
                result.preamble.append(line)
            else:
                current.lines.append(line)
        return result

    def extend_text(self, text: str) -> None:
        fragment = self.parse(text)
        for section in fragment.sections:
            self.add(section)

    def add(self, section: IniSectionIR) -> IniSectionIR:
        section.ordinal = self._next_ordinal
        self._next_ordinal += 1
        self.sections.append(section)
        return section

    def add_section(
            self,
            name: str,
            lines: Iterable[str],
            *,
            phase: IniPhase,
            ib_order: int = 0,
            global_component: Optional[int] = None,
            role: str = "",
            definitions: Iterable[str] = (),
            references: Iterable[str] = (),
    ) -> IniSectionIR:
        return self.add(IniSectionIR(
            name=name,
            lines=list(lines),
            phase=phase,
            ib_order=ib_order,
            global_component=global_component,
            role=role,
            definitions=tuple(definitions),
            references=tuple(references),
        ))

    def get(self, name: str) -> IniSectionIR:
        key = name.casefold()
        matches = [section for section in self.sections
                   if section.name.casefold() == key]
        if len(matches) != 1:
            raise CrossSceneCompileError(
                f"expected exactly one [{name}] section, found {len(matches)}")
        return matches[0]

    def ordered_sections(self) -> List[IniSectionIR]:
        return sorted(self.sections, key=self.layout.key)

    def render(self) -> str:
        lines = list(self.preamble)
        phase = None
        for section in self.ordered_sections():
            if section.phase != phase:
                if lines and lines[-1] != "":
                    lines.append("")
                lines.append(
                    f"; ===== {_PHASE_TITLES[section.phase]} =====")
                phase = section.phase
            if lines and lines[-1] != "":
                lines.append("")
            lines.append(f"[{section.name}]")
            lines.extend(section.lines)
        if self.footer:
            if lines and lines[-1] != "":
                lines.append("")
            lines.extend(self.footer)
        return "\n".join(lines).rstrip() + "\n"

    def assert_unique(self) -> None:
        seen: Dict[str, str] = {}
        duplicates = []
        for section in self.sections:
            key = section.name.casefold()
            if key in seen:
                duplicates.append(f"[{seen[key]}] / [{section.name}]")
            else:
                seen[key] = section.name
        if duplicates:
            raise CrossSceneCompileError(
                "case-insensitive duplicate INI sections: " + ", ".join(duplicates))


